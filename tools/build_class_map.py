"""
Build configs/detector_class_map.json for a detector whose classes are *units on the field*
(e.g. SudhishNeel/clash-royale-detector: `skeleton`, `golemite`, `knight-evolution`, ...).

The companion counts *card plays*, so every class must map to the card that deploys it,
or to null when it is never a play by itself (towers, death spawns, ability effects).
Units that some other card also spawns (skeletons from a Graveyard, goblins from a Goblin
Barrel, ...) get `spawned_by` hints so the play tracker attributes them to the parent play.

    python tools/build_class_map.py pretrained_weights/sudhishneel_v8/names.json
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "configs" / "detector_class_map.json"
COSTS = ROOT / "configs" / "card_costs_hf.json"

# unit name -> card id, where they differ
UNIT_TO_CARD = {
    "archer": "archers", "barbarian": "barbarians", "bat": "bats", "skeleton": "skeletons",
    "goblin": "goblins", "minion": "minions", "guard": "guards", "elite-barbarian": "elite_barbarians",
    "spear-goblin": "spear_goblins", "wall-breaker": "wall_breakers", "royal-hog": "royal_hogs",
    "royal-recruit": "royal_recruits", "rascal-boy": "rascals", "rascal-girl": "rascals",
    "zappy": "zappies", "elixir-golem-big": "elixir_golem", "phoenix-big": "phoenix",
    "hog-rider": "hog_rider", "the-log": "the_log", "skeleton-dragon": "skeleton_dragons",
}
# never a card play by itself
IGNORE = {
    "king-tower", "queen-tower", "cannoneer-tower", "dagger-duchess-tower", "royal-guardian",
    "golemite", "lava-pup", "elixir-golem-mid", "elixir-golem-small", "phoenix-egg", "phoenix-small",
    "skeleton-king-skill", "bomb", "dirt", "elixir", "clock", "goblin-brawler", "baby-goblin", "hog",
    "goblin-ball", "party-rocket", "axe",
}
# units per play for multi-unit cards (how many detections one play produces)
UNITS_PER_PLAY = {
    "archers": 2, "barbarians": 5, "bats": 5, "skeletons": 3, "goblins": 4, "minions": 3, "guards": 3,
    "elite_barbarians": 2, "spear_goblins": 3, "wall_breakers": 2, "royal_hogs": 4, "royal_recruits": 6,
    "rascals": 3, "zappies": 3,
}
# a unit of the key card may come from these cards instead of being its own play
SPAWNED_BY = {
    "skeletons": ["graveyard", "witch", "tombstone", "skeleton_barrel", "skeleton_army", "giant_skeleton",
                  "skeleton_king", "skeleton_dragons"],
    "goblins": ["goblin_barrel", "goblin_hut", "goblin_gang", "goblin_drill", "goblin_cage", "goblin_machine"],
    "spear_goblins": ["goblin_hut", "goblin_gang"],
    "barbarians": ["barbarian_hut", "barbarian_barrel", "barbarian_launcher"],
    "bats": ["night_witch"],
    "minions": ["minion_horde"],
}


def to_card(name: str, costs: dict) -> tuple:
    """-> (card_id or None, evolved?, reason)."""
    base, evolved = name, False
    for suffix in ("-evolution", "-hero"):
        if base.endswith(suffix):
            base, evolved = base[: -len(suffix)], suffix == "-evolution"
    if name in IGNORE or base in IGNORE:
        return None, evolved, "not a play (tower / spawn / effect)"
    card = UNIT_TO_CARD.get(base, base.replace("-", "_"))
    if card not in costs:
        return None, evolved, f"no card '{card}' in card_costs_hf.json"
    return card, evolved, ""


def build(names: list, out: Path, input_size: int, crop: tuple) -> dict:
    costs = json.loads(COSTS.read_text(encoding="utf-8"))["costs"]
    classes, report = [], []
    for i, n in enumerate(names):
        card, evolved, why = to_card(n, costs)
        classes.append({"index": i, "name": n, "card": card, "side": None, "evolved": evolved})
        if card is None:
            report.append(f"  {i:3d} {n:<28} -> ignored: {why}")
    data = {
        "_doc": "Generated by tools/build_class_map.py. Classes are units; 'card' is the card that deploys them. "
                "side=null: owner inferred from where the unit is first deployed.",
        "input_size": input_size,
        "arena_crop": list(crop),
        "side_mode": "position",   # or "color": read the health-bar colour (only works when a bar shows)
        "units_per_play": UNITS_PER_PLAY,
        "spawned_by": SPAWNED_BY,
        "classes": classes,
    }
    out.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    mapped = sum(1 for c in classes if c["card"])
    print(f"{len(names)} classes -> {mapped} mapped to cards, {len(names) - mapped} ignored -> {out}")
    print("\n".join(report))
    return data


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("names_json", type=Path, help="JSON list of class names in model order")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--input-size", type=int, default=800)
    ap.add_argument("--crop", type=int, nargs=2, default=(568, 896), help="arena crop the model expects (w h)")
    a = ap.parse_args()
    build(json.loads(a.names_json.read_text(encoding="utf-8")), a.out, a.input_size, tuple(a.crop))


if __name__ == "__main__":
    main()
